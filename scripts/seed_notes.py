#!/usr/bin/env python3
"""
seed_notes.py — Початковий засів бази даних нотатками з фіксованим seed.
Використовує швидку пакетну вставку (COPY) через psycopg.
"""

import argparse
import io
import random
import sys
import time
from datetime import datetime, timezone
import psycopg

def parse_args():
    parser = argparse.ArgumentParser(description="Seed PostgreSQL database with deterministic notes.")
    parser.add_argument("--host", default="127.0.0.1", help="PostgreSQL host (default: 127.0.0.1)")
    parser.add_argument("--port", type=int, default=5432, help="PostgreSQL port (default: 5432)")
    parser.add_argument("--user", default="repl_admin", help="PostgreSQL user (default: repl_admin)")
    parser.add_argument("--password", default="repl_password_a", help="PostgreSQL password")
    parser.add_argument("--dbname", default="notes_a", help="PostgreSQL database name (default: notes_a)")
    parser.add_argument("--count", type=int, default=100000, help="Number of notes to generate (default: 100000)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for deterministic generation (default: 42)")
    parser.add_argument("--batch-size", type=int, default=10000, help="Batch size for COPY insertion (default: 10000)")
    return parser.parse_args()

def generate_csv_batch(start_idx: int, batch_size: int, rng: random.Random) -> io.StringIO:
    buf = io.StringIO()
    base_time = datetime(2026, 1, 1, 0, 0, 0, tzinfo=timezone.utc)
    for i in range(start_idx, start_idx + batch_size):
        author_id = f"author_{(rng.randint(1, 1000))}"
        title = f"Deterministic Note #{i} [seed-key-{rng.randint(100000, 999999)}]"
        body = f"Payload body for note #{i}. Deterministic text content generated with seed. Random token: {rng.getrandbits(32):x}."
        # Clean title and body for tab-separated COPY format
        title_clean = title.replace("\t", " ").replace("\n", " ")
        body_clean = body.replace("\t", " ").replace("\n", " ")
        updated_at = base_time.isoformat()
        # id is auto-generated by sequence, so columns: author_id, title, body, updated_at
        buf.write(f"{author_id}\t{title_clean}\t{body_clean}\t{updated_at}\n")
    buf.seek(0)
    return buf

def main():
    args = parse_args()
    print(f"[{datetime.now().isoformat()}] Starting seeding: count={args.count}, seed={args.seed}, target={args.host}:{args.port}/{args.dbname}")
    
    rng = random.Random(args.seed)
    conn_str = f"host={args.host} port={args.port} dbname={args.dbname} user={args.user} password={args.password}"
    
    start_time = time.time()
    total_inserted = 0
    
    try:
        with psycopg.connect(conn_str) as conn:
            with conn.cursor() as cur:
                # Ensure table exists
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS notes (
                        id BIGSERIAL PRIMARY KEY,
                        author_id VARCHAR(64) NOT NULL,
                        title VARCHAR(255) NOT NULL,
                        body TEXT NOT NULL,
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                    );
                """)
                conn.commit()

                # Insert in batches using COPY
                while total_inserted < args.count:
                    batch_len = min(args.batch_size, args.count - total_inserted)
                    csv_data = generate_csv_batch(total_inserted + 1, batch_len, rng)
                    
                    with cur.copy("COPY notes (author_id, title, body, updated_at) FROM STDIN WITH (FORMAT text)") as copy:
                        copy.write(csv_data.getvalue())
                    
                    conn.commit()
                    total_inserted += batch_len
                    elapsed = time.time() - start_time
                    rate = total_inserted / elapsed if elapsed > 0 else 0
                    print(f"[{datetime.now().isoformat()}] Inserted {total_inserted}/{args.count} notes ({rate:.1f} notes/sec)...")

                cur.execute("SELECT count(*), min(id), max(id) FROM notes;")
                cnt, min_id, max_id = cur.fetchone()
                print(f"[{datetime.now().isoformat()}] SUCCESS: Database now contains {cnt} notes (ID range: {min_id} - {max_id}).")
                print(f"Total time: {time.time() - start_time:.2f} seconds.")

    except Exception as e:
        print(f"ERROR during seeding: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()

